    from torchinfo import summary


    class configs():
        def __init__(self):
            self.factor = 3
            self.embed = 'timeF'
            self.freq = 'ts'
            self.seq_len = 60
            self.label_len = 30
            self.pred_len = 30
            self.output_attention = False
            self.d_model = 512
            self.d_ff = 2048
            self.activation = 'gelu'
            self.dropout = 0.05
            self.enc_in = 25
            self.dec_in = 25
            self.c_out = 25
            self.e_layers = 2
            self.d_layers = 1
            self.moving_avg = 25
            self.n_heads = 9

    model = Model(configs())
    summary(model, input_size=[(16,60,25), (16,60,1), (16,60,25), (16,60,1)])